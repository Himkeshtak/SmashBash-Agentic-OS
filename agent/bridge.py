import os
import re

import pexpect


PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XV6_DIR = os.path.join(PROJECT_ROOT, "xv6")

QEMU_PATH = "/home/akshaya/minor-project/qemu/build/qemu-system-riscv64"

ALLOWED_FILES = {
    "README",
    "report.txt",
    "inbox.txt",
}

PATH_PATTERN = re.compile(r"^[A-Za-z0-9_.-]{1,100}$")


class BridgeError(RuntimeError):
    """Raised when communication with xv6 fails."""


class QEMUBridge:
    def __init__(self, timeout=15):
        self.timeout = timeout
        self.child = None

    def start(self):
        """Start xv6 and wait for its shell prompt."""

        if self.child is not None and self.child.isalive():
            return

        if not os.path.isfile(QEMU_PATH):
            raise BridgeError(f"QEMU not found: {QEMU_PATH}")

        if not os.path.isfile(os.path.join(XV6_DIR, "Makefile")):
            raise BridgeError(f"xv6 source not found: {XV6_DIR}")

        self.child = pexpect.spawn(
            "make",
            ["qemu", f"QEMU={QEMU_PATH}"],
            cwd=XV6_DIR,
            encoding="utf-8",
            timeout=self.timeout,
        )

        try:
            self.child.expect(r"\$ ")
        except (pexpect.TIMEOUT, pexpect.EOF) as exc:
            output = self.child.before
            self.close()
            raise BridgeError(
                f"xv6 failed to boot. Output:\n{output}"
            ) from exc

    def _execute_fixed_command(self, command):
        """Execute a command generated by the bridge."""

        if self.child is None or not self.child.isalive():
            raise BridgeError("QEMU is not running.")

        try:
            self.child.sendline(command)
            self.child.expect(r"\$ ")
            return self.child.before.strip()

        except pexpect.TIMEOUT as exc:
            self.close()
            raise BridgeError("Timed out waiting for xv6.") from exc

        except pexpect.EOF as exc:
            self.close()
            raise BridgeError("QEMU exited unexpectedly.") from exc

    def list_files(self):
        """List files in the xv6 guest filesystem."""

        output = self._execute_fixed_command("ls")

        return {
            "ok": True,
            "files_output": output,
            "source": "xv6",
        }

    def read_file(self, path):
        """Read an approved file from the xv6 guest."""

        if not isinstance(path, str):
            raise BridgeError("Path must be a string.")

        normalized_path = path.lstrip("/")

        if not PATH_PATTERN.fullmatch(normalized_path):
            raise BridgeError("Invalid file path.")

        if normalized_path not in ALLOWED_FILES:
            raise BridgeError(
                f"File is not in the bridge allowlist: {normalized_path}"
            )

        output = self._execute_fixed_command(f"cat {normalized_path}")

        return {
            "ok": True,
            "path": normalized_path,
            "content": output,
            "source": "xv6",
        }

    def close(self):
        """Stop the QEMU process started by this bridge."""

        if self.child is None:
            return

        try:
            if self.child.isalive():
                # Standard QEMU terminal escape: Ctrl+A, then X.
                self.child.sendcontrol("a")
                self.child.send("x")

                try:
                    self.child.expect(pexpect.EOF, timeout=5)
                except (pexpect.TIMEOUT, pexpect.EOF):
                    if self.child.isalive():
                        self.child.terminate(force=True)

        finally:
            self.child.close()
            self.child = None

    def __enter__(self):
        self.start()
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        self.close()